const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const projectRoot = path.resolve(__dirname, '..');

function importModule(fileName) {
    return import(pathToFileURL(path.join(projectRoot, fileName)).href);
}

const NAT_ROUTES =
    'Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\n' +
    'eth0\t00000000\t01101DAC\t0003\t0\t0\t0\t00000000\n' +
    'eth0\t00101DAC\t00000000\t0001\t0\t0\t0\t00F0FFFF\n';
const TUNNELED_RESOLV = '# generated by WSL\nnameserver 10.255.255.254\n';

test('wsl host ip prefers the gateway over the dns-tunneling virtual', async () => {
    const { parseDefaultGateway, wslHostIpFromSources } =
        await importModule('scripts/rl/chrome.mjs');
    assert.equal(parseDefaultGateway(NAT_ROUTES), '172.29.16.1');
    assert.equal(parseDefaultGateway(''), null);
    // The regression: 10.255.255.254 is not dialable, so the gateway wins.
    assert.equal(wslHostIpFromSources(NAT_ROUTES, TUNNELED_RESOLV), '172.29.16.1');
    // Without a route table, a real nameserver still works as fallback.
    assert.equal(wslHostIpFromSources('', 'nameserver 172.29.16.1\n'), '172.29.16.1');
    // But the tunneling virtual alone resolves to nothing, not to itself.
    assert.equal(wslHostIpFromSources('', TUNNELED_RESOLV), null);
});
